INSERT INTO USER_ROLES (USER_ROLE_ID, USER_ID, ROLE_ID, CREATED_AT)
SELECT SEQ_USER_ROLES.NEXTVAL, u.USER_ID, r.ROLE_ID, SYSTIMESTAMP
FROM USERS u
JOIN ROLES r ON r.ROLE_CODE = 'ADMIN'
WHERE u.LOGIN_ID = 'admin'
  AND NOT EXISTS (
      SELECT 1
      FROM USER_ROLES ur
      WHERE ur.USER_ID = u.USER_ID
        AND ur.ROLE_ID = r.ROLE_ID
  );

COMMIT;

INSERT INTO ROLE_PERMISSIONS (ROLE_PERMISSION_ID, ROLE_ID, PERMISSION_ID, CREATED_AT)
SELECT SEQ_ROLE_PERMISSIONS.NEXTVAL, r.ROLE_ID, p.PERMISSION_ID, SYSTIMESTAMP
FROM ROLES r
JOIN PERMISSIONS p ON p.PERMISSION_CODE IN (
    'dashboard.read',
    'users.read',
    'users.write',
    'roles.read',
    'roles.write'
)
WHERE r.ROLE_CODE = 'TEAM_MANAGER'
  AND p.USE_YN = 'Y'
  AND NOT EXISTS (
      SELECT 1
      FROM ROLE_PERMISSIONS rp
      WHERE rp.ROLE_ID = r.ROLE_ID
        AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

COMMIT;

